-- 1) טבלת העסקים: כל עסק = שורה אחת, עם מזהה מספרי (1, 2, 3...)
create table if not exists public.businesses (
  id             bigint generated by default as identity primary key,  -- המפתח של העסק
  slug           text not null unique,        -- שם באנגלית לכתובת ולקוד (למשל super-mafteach)
  name           text not null,               -- שם העסק להצגה
  address        text,
  place_id       text,                        -- Place ID של גוגל
  maps_query     text,                        -- גיבוי אם אין Place ID
  whatsapp       text,                        -- מספר בפורמט 972...
  whatsapp_text  text,
  google_rating  numeric(2,1),                -- דירוג להצגה על המסך (מתעדכן ידנית)
  google_reviews integer,                     -- מספר ביקורות להצגה על המסך
  active         boolean not null default true,
  created_at     timestamptz not null default now()
);

-- 2) טבלת האירועים: כל נגיעה / סריקה = שורה אחת, מקושרת לעסק לפי המספר שלו
create table if not exists public.events (
  id             bigint generated always as identity primary key,
  business_id    bigint not null references public.businesses (id) on delete restrict,
  created_at     timestamptz not null default now(),
  event          text not null,
  source         text,
  device         text
);
create index if not exists events_bizid_time_idx on public.events (business_id, created_at desc);
create index if not exists events_bizid_id_idx   on public.events (business_id, id desc);

-- 3) אבטחה: הדפים יכולים רק לקרוא פרטי עסק פעיל ולרשום אירוע דרך הפונקציה
alter table public.businesses enable row level security;
alter table public.events     enable row level security;

drop policy if exists "read active businesses" on public.businesses;
create policy "read active businesses" on public.businesses
  for select to anon, authenticated using (active);

grant select on public.businesses to anon, authenticated;
revoke all on public.events from anon, authenticated;

-- 4) רישום אירוע: הדף שולח את שם העסק (או את המספר שלו), והפונקציה שומרת לפי המספר
create or replace function public.log_event(
  p_biz text, p_event text, p_source text default null, p_device text default null
) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
begin
  if p_biz is null or coalesce(p_event, '') = '' then return; end if;
  select id into v_id from businesses
  where (slug = p_biz or id::text = p_biz) and active
  limit 1;
  if v_id is null then return; end if;
  insert into events (business_id, event, source, device)
  values (v_id, left(p_event, 80), left(p_source, 30), left(p_device, 30));
end;
$$;
revoke all on function public.log_event(text, text, text, text) from public;
grant execute on function public.log_event(text, text, text, text) to anon, authenticated;

-- 5) "תודה" חיה: הסריקה האחרונה של עסק (מחזיר רק מספר, בלי מידע על אנשים)
create or replace function public.latest_scan(p_biz text)
returns table (id bigint, event text)
language sql
stable
security definer
set search_path = public
as $$
  select e.id, e.event
  from events e
  join businesses b on b.id = e.business_id
  where (b.slug = p_biz or b.id::text = p_biz)
    and e.event in ('סריקה לגוגל', 'פתיחת וואטסאפ')
  order by e.id desc
  limit 1;
$$;
revoke all on function public.latest_scan(text) from public;
grant execute on function public.latest_scan(text) to anon, authenticated;

-- 6) תצוגות לקריאה נוחה (רק לך, בדשבורד – לא חשופות לדפים)
create or replace view public.events_view with (security_invoker = true) as
select
  e.id,
  to_char(e.created_at at time zone 'Asia/Jerusalem', 'YYYY-MM-DD') as date,
  to_char(e.created_at at time zone 'Asia/Jerusalem', 'HH24:MI')    as time,
  e.business_id,
  b.name as business_name,
  b.slug as business_slug,
  e.event, e.source, e.device
from public.events e
join public.businesses b on b.id = e.business_id
order by e.created_at desc;

create or replace view public.monthly_summary with (security_invoker = true) as
select
  e.business_id,
  b.name as business_name,
  to_char(e.created_at at time zone 'Asia/Jerusalem', 'YYYY-MM') as month,
  e.event,
  count(*) as total
from public.events e
join public.businesses b on b.id = e.business_id
group by e.business_id, b.name, 3, e.event
order by e.business_id, 3 desc, total desc;

revoke all on public.events_view, public.monthly_summary from anon, authenticated;

